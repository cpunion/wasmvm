#!/usr/bin/env python3
"""Generate exact filesystem provider contracts from pinned WASI 0.3.2 WIT."""
import hashlib,json,subprocess,tarfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
INPUT=ROOT/'artifacts/components/wasi-inputs/preview3/wasi-wit-0.3.2'
ARCHIVE=INPUT.with_name(INPUT.name+'.tar.gz')
SHA='2e918e047c6ad251a44b4d1141359495a27219058fd7090f8b8142f6bc0ec311'
assert hashlib.sha256(ARCHIVE.read_bytes()).hexdigest()==SHA
assert subprocess.check_output(['wasm-tools','--version'],text=True).strip()=='wasm-tools 1.258.0'
with tarfile.open(ARCHIVE) as a:
 for member in a.getmembers():
  if member.name.startswith('wasi-wit-0.3.2/filesystem/') and member.name.endswith('.wit'):
   assert (INPUT.parent/member.name).read_bytes()==a.extractfile(member).read()
graph=json.loads(subprocess.check_output(['wasm-tools','component','wit',str(INPUT/'filesystem'),'--json'],text=True))
q=json.dumps
scalar=lambda k:'&witShape{kind:component.Kind'+k.upper()[0]+k[1:]+'}'
def ref(t):return 'nil' if t is None else 's['+str(t)+']' if isinstance(t,int) else scalar(t)
def resource(i):
 t=graph['types'][i]
 if isinstance(t['kind'],dict):return resource(t['kind']['type'])
 assert t['kind']=='resource';return t['name']
def shape(t):
 k=t['kind']
 if k=='resource':return '&witShape{resource:'+q(t['name'])+'}'
 kind,v=next(iter(k.items()))
 if kind=='type':return ref(v)
 if kind=='handle':
  handle,index=next(iter(v.items()));return '&witShape{kind:component.Kind'+handle.title()+',resource:'+q(resource(index))+'}'
 if kind in ['list','option','future','stream']:return '&witShape{kind:component.Kind'+kind.title()+',element:'+ref(v)+'}'
 if kind in ['enum','flags']:return '&witShape{kind:component.Kind'+kind.title()+',labels:[]string{'+','.join(q(x['name']) for x in v['cases' if kind=='enum' else 'flags'])+'}}'
 if kind=='record':fields=[(f['name'],f['type']) for f in v['fields']]
 elif kind=='variant':fields=[(f['name'],f['type']) for f in v['cases']]
 elif kind=='tuple':fields=[('',t) for t in v['types']]
 elif kind=='result':fields=[('',v['ok']),('',v['err'])]
 else:raise ValueError(kind)
 return '&witShape{kind:component.Kind'+kind.title()+',fields:[]witField{'+','.join('{'+q(name)+','+ref(t)+'}' for name,t in fields)+'}}'
lines=['// Code generated by build_preview3_filesystem_schema.py; DO NOT EDIT.','// WASI 0.3.2 WIT: Apache-2.0 WITH LLVM-exception.','package preview3','import "github.com/cpunion/wasmvm/pkg/component"','var filesystemWITTypes=func()[]*witShape{','s:=make([]*witShape,'+str(len(graph['types']))+')']
for i,t in enumerate(graph['types']):lines+=['s['+str(i)+']='+shape(t)]
lines+=['return s','}()','var filesystemWITFunctions=func()map[string]map[string]*witFunction{','s:=filesystemWITTypes;_ = s','return map[string]map[string]*witFunction{']
for interface in graph['interfaces']:
 if interface['package']!=len(graph['packages'])-1:continue
 lines+=[q(interface['name'])+':{']
 for name,f in interface['functions'].items():
  async_='async' in json.dumps(f['kind'])
  lines+=[q(name)+':{async:'+str(async_).lower()+',parameters:[]*witShape{'+','.join(ref(p['type']) for p in f['params'])+'},result:'+ref(f['result'])+'},']
 lines+=['},']
lines+=['}','}()','var filesystemWITNamedTypes=map[string]*witShape{']
interface=next(i for i in graph['interfaces'] if i['name']=='types' and i['package']==len(graph['packages'])-1)
for name,index in interface['types'].items():lines+=[q(name)+':filesystemWITTypes['+str(index)+'],']
lines+=['}']
output=ROOT/'pkg/wasi/preview3/filesystem_schema.go';output.write_text('\n'.join(lines)+'\n')
subprocess.run(['gofmt','-w',str(output)],check=True)
( output.parent/'testdata/filesystem-schema.json').write_text(json.dumps({'wasiVersion':'0.3.2','witArchiveSHA256':SHA,'producer':'wasm-tools 1.258.0','generatorSHA256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'schemaSHA256':hashlib.sha256(output.read_bytes()).hexdigest()},indent=2)+'\n')
print('Generated pinned filesystem contracts')
